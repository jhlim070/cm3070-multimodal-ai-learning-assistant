"""
Centralised input validation for the multimodal AI learning assistant.

This module validates user identifiers, chat input, profile topics, uploaded
documents, and chat images before they reach downstream components. It applies
length, format, size, and file-content checks to reduce malformed input,
resource-exhaustion risks, unsafe file handling, and invalid downstream
identifiers.
"""

import hashlib
import os
import re
import zipfile

# Limits -----------------------------------------------------------------
MAX_USER_ID_LEN = 64
MAX_QUESTION_CHARS = 2000
MAX_TOPICS_CHARS = 300
MAX_TOPICS_COUNT = 10
# Maximum uploaded file size
MAX_FILE_BYTES = 50 * 1024 * 1024
# Maximum chat-image size
MAX_IMAGE_BYTES = 10 * 1024 * 1024         
# Maximum OOXML expansion size
MAX_ZIP_UNCOMPRESSED_BYTES = 500 * 1024 * 1024   

ALLOWED_DOC_EXTENSIONS = {".pdf", ".docx", ".pptx", ".png", ".jpg", ".jpeg"}
ALLOWED_IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg"}

# Restrict user IDs to characters that are safe for 
# downstream storage and identifier construction.
USER_ID_RE = re.compile(r"^[A-Za-z0-9._@\- ]+$")

# Remove non-printable C0 control characters while preserving 
# common whitespace characters used in user input.
_CONTROL_CHARS = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")

# File signatures used to verify that the file content is consistent with its
# declared extension.
_MAGIC = {
    ".pdf": [b"%PDF"],
    ".png": [b"\x89PNG\r\n\x1a\n"],
    ".jpg": [b"\xff\xd8\xff"],
    ".jpeg": [b"\xff\xd8\xff"],
    ".docx": [b"PK\x03\x04", b"PK\x05\x06", b"PK\x07\x08"],
    ".pptx": [b"PK\x03\x04", b"PK\x05\x06", b"PK\x07\x08"],
}

# Required internal files used to distinguish DOCX 
# and PPTX packages from arbitrary ZIP archives.
_OOXML_MARKER = {
    ".docx": "word/document.xml",
    ".pptx": "ppt/presentation.xml",
}


def strip_control_chars(text):
    """
    Remove non-printable C0 control characters while preserving common whitespace.
    """
    return _CONTROL_CHARS.sub("", text or "")


# User ID --------------------------------------------------------------------------
def validate_user_id(raw):
    """
    Validate and normalise a user ID.

    Returns `(ok, cleaned_user_id, message)`. This function validates the format
    of the identifier; it does not authenticate the user.
    """
    uid = strip_control_chars(raw).strip()
    if not uid:
        return False, "", "Please enter a User ID to continue."
    if len(uid) > MAX_USER_ID_LEN:
        return False, "", f"User ID is too long (max {MAX_USER_ID_LEN} characters)."
    if not USER_ID_RE.match(uid):
        return False, "", ("User ID may only contain letters, numbers, spaces, "
                           "and the characters . _ - @")
    return True, uid, ""

# Sanitisation can map different user IDs to the same collection name.
# Acceptable for the current single-user deployment but would require
# collision-resistant identifiers in a multi-user deployment.
def sanitise_for_collection(user_id):
    """
    Convert a validated user ID into a ChromaDB-compatible collection-name
    fragment.

    Characters outside the collection-name character set are replaced with
    underscores, and the result is limited in length.
    """
    safe = re.sub(r"[^A-Za-z0-9_-]", "_", (user_id or "").strip().lower())
    safe = safe.strip("_-")
    if not safe:
        safe = "user"
    return safe[:40]


# --- Chat message -----------------------------------------------------------
def validate_question(raw, max_chars=MAX_QUESTION_CHARS):
    """
    Validate and clean a learner's question.

    Returns `(ok, cleaned_question, message)`. The length limit bounds the amount
    of user-controlled text passed to downstream embedding and generation stages.
    """
    q = strip_control_chars(raw).strip()
    if not q:
        return False, "", "Please type a question."
    # A larger limit may be supplied when validating a machine-augmented query,
    # such as one containing an image description generated by the vision model.
    if len(q) > max_chars:
        return False, "", (f"That question is {len(q)} characters long; the limit is "
                           f"{max_chars}. Please shorten it.")
    return True, q, ""


# --- Profile topics ---------------------------------------------------------
def validate_topics(raw):
    """
    Validate and normalise the learner's profile topics.

    Returns `(ok, cleaned_topics, message)`, where valid topics are returned as a
    comma-separated string.
    """
    text = strip_control_chars(raw or "").strip()
    if len(text) > MAX_TOPICS_CHARS:
        return False, "", f"Topics list is too long (max {MAX_TOPICS_CHARS} characters)."
    parts = [p.strip() for p in text.split(",")]
    parts = [p for p in parts if p]
    if len(parts) > MAX_TOPICS_COUNT:
        return False, "", f"Please list at most {MAX_TOPICS_COUNT} topics."
    for p in parts:
        if len(p) > 60:
            return False, "", f"Topic \"{p[:30]}...\" is too long (max 60 characters each)."
    return True, ", ".join(parts), ""


# Files ------------------------------------------------------------------
def sha256_file(path, chunk_size=1024 * 1024):
    """
    Return the SHA-256 hash of a file's contents.
    """

    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(chunk_size), b""):
            h.update(block)
    return h.hexdigest()


def safe_display_name(path):
    """
    Return a cleaned base filename with any directory components removed.

    The returned name is suitable for display and for use as document-source
    metadata.
    """
    name = os.path.basename(path or "")
    name = strip_control_chars(name).strip()
    return name or "unnamed file"


def _magic_ok(path, ext):
    expected = _MAGIC.get(ext)
    if not expected:
        return True
    try:
        with open(path, "rb") as fh:
            head = fh.read(8)
    except OSError:
        return False
    return any(head.startswith(sig) for sig in expected)


def _ooxml_ok(path, ext):
    """
    Validate an Office Open XML package and limit its total uncompressed size.
    """
    marker = _OOXML_MARKER.get(ext)
    if not marker:
        return True, ""
    try:
        with zipfile.ZipFile(path) as zf:
            names = zf.namelist()
            total = sum(info.file_size for info in zf.infolist())
    except (zipfile.BadZipFile, OSError):
        return False, "file is not a readable Office document"
    if total > MAX_ZIP_UNCOMPRESSED_BYTES:
        return False, "file expands to an implausible size and was rejected"
    if marker not in names:
        return False, f"file does not look like a valid {ext} document"
    return True, ""


def validate_upload(path):
    """
    Validate a study-material upload.

    Returns `(ok, display_name, message)`. Validation performs inexpensive checks
    before format-specific inspection so invalid files are rejected early.
    """

    name = safe_display_name(path)
    ext = os.path.splitext(name)[1].lower()

    if ext not in ALLOWED_DOC_EXTENSIONS:
        allowed = ", ".join(sorted(ALLOWED_DOC_EXTENSIONS))
        return False, name, f"unsupported file type \"{ext or 'none'}\" (allowed: {allowed})"

    try:
        size = os.path.getsize(path)
    except OSError:
        return False, name, "file could not be read"
    if size == 0:
        return False, name, "file is empty"
    if size > MAX_FILE_BYTES:
        mb = MAX_FILE_BYTES // (1024 * 1024)
        return False, name, f"file is larger than the {mb} MB limit"

    if not _magic_ok(path, ext):
        return False, name, (f"file contents do not match its .{ext.lstrip('.')} extension "
                             f"-- it may be renamed or corrupt")

    ok, msg = _ooxml_ok(path, ext)
    if not ok:
        return False, name, msg

    return True, name, ""


def validate_chat_image(path):
    """
    Validate an optional image attached to a chat question.

    Only PNG and JPEG images within the configured size limit are accepted.
    """
    if not path:
        return True, ""
    name = safe_display_name(path)
    ext = os.path.splitext(name)[1].lower()
    if ext not in ALLOWED_IMAGE_EXTENSIONS:
        return False, "Only PNG and JPEG images can be attached to a question."
    try:
        size = os.path.getsize(path)
    except OSError:
        return False, "That image could not be read."
    if size == 0:
        return False, "That image file is empty."
    if size > MAX_IMAGE_BYTES:
        mb = MAX_IMAGE_BYTES // (1024 * 1024)
        return False, f"That image is larger than the {mb} MB limit."
    if not _magic_ok(path, ext):
        return False, "That file does not appear to be a real PNG or JPEG image."
    return True, ""
